import type { components } from '@triage/ts-clients/gateway';

import { decodeCursor, demoFile, encodeCursor } from './investigations.ts';

const ID = '9f8b6c1e-3d2a-4f5b-8e7d-6c5b4a392817';
const encode = (value: unknown) => Buffer.from(JSON.stringify(value)).toString('base64url');

describe('cursor', () => {
  it('decodes what it encodes, to the microsecond', () => {
    const at = '2026-10-15T04:44:39.473995Z';
    expect(decodeCursor(encodeCursor(at, ID))).toEqual([at, ID]);
  });

  it('refuses anything else, impossible instants included', () => {
    for (const cursor of [
      'forged',
      encode(['2026-02-31T00:00:00.000000Z', ID]),
      encode(['2026-10-15T25:00:00.000000Z', ID]),
      encode(['2026-10-15T04:44:39.473Z', ID]),
      encode(['2026-10-15T04:44:39.473995Z', 'not-a-uuid']),
      encode(['2026-10-15T04:44:39.473995Z']),
    ]) {
      expect(decodeCursor(cursor)).toBeUndefined();
    }
  });
});

describe('demoFile', () => {
  const OTHER = '5b1c9d2e-7f3a-4e8b-9c6d-1a2b3c4d5e6f';
  const run = (source: 'live' | 'sim'): components['schemas']['Investigation'] => ({
    id: ID,
    group_id: OTHER,
    title: 'HighErrorRate on checkout',
    status: 'awaiting_approval',
    verdict: null,
    created_at: '2026-10-20T12:00:00.000Z',
    updated_at: '2026-10-20T12:01:30.000Z',
    source,
    cause: null,
    plan_status: null,
    summary: 'checkout v1.8.0 raised the 5xx rate.',
    tokens_used: 41_200,
    hypotheses: [],
    missing_evidence: [],
    partial: false,
    models: [],
    proposed_actions: [],
    plan: null,
    steps: [],
  });
  const store = (source: 'live' | 'sim') => (id: string) =>
    Promise.resolve(id === ID ? run(source) : undefined);

  it('writes simulated investigations as a typed module for the web demo', async () => {
    const file = await demoFile(store('sim'), [ID]);
    expect(file).toMatch(/^\/\/ Generated by `make demo-save`/);
    expect(file).toContain("import type { Investigation } from '../../lib/investigations.ts';");
    expect(file).toContain('export const EVAL_RUNS = [');
    expect(file).toContain(`"id": "${ID}"`);
    expect(file.trimEnd()).toMatch(/\] satisfies Investigation\[\];$/);
  });

  it('refuses a live investigation, an unknown id, one that is no uuid, and none at all', async () => {
    await expect(demoFile(store('live'), [ID])).rejects.toThrow(
      `${ID} is live: only simulated investigations may be saved`,
    );
    await expect(demoFile(store('sim'), [OTHER])).rejects.toThrow(
      `no investigation has id ${OTHER}`,
    );
    await expect(demoFile(store('sim'), ['../web'])).rejects.toThrow('../web is no uuid');
    await expect(demoFile(store('sim'), [])).rejects.toThrow('name at least one investigation');
  });
});
