"""Regenerates src/py_clients/generated/ from contracts/. Run through `make codegen`."""

import os
import shutil
from pathlib import Path

from datamodel_code_generator.__main__ import Exit, main

# datamodel-codegen reads its settings from the root pyproject.toml, found from the working dir.
os.chdir(Path(__file__).resolve().parents[3])
OUT = Path("packages/py-clients/src/py_clients/generated")
SOURCES = (
    ("messages", "jsonschema", "messages"),
    ("openapi/gateway.yaml", "openapi", "gateway.py"),
    ("openapi/agent.yaml", "openapi", "agent.py"),
)

# Start empty so models of deleted contracts disappear.
shutil.rmtree(OUT, ignore_errors=True)
OUT.mkdir()
(OUT / "__init__.py").write_text(
    '"""Generated by `make codegen` from contracts/. Do not edit."""\n', newline="\n"
)
for source, kind, target in SOURCES:
    args = ["--input", f"contracts/{source}", "--input-file-type", kind]
    if main([*args, "--output", str(OUT / target)]) != Exit.OK:
        raise SystemExit(f"datamodel-codegen failed on contracts/{source}")
