// Regenerates src/generated/ from contracts/. Run through `make codegen`.
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { generate } from '@graphql-codegen/cli';
import { compileFromFile } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';

const contracts = new URL('../../../contracts/', import.meta.url);
const out = new URL('../src/generated/', import.meta.url);
const banner = '// Generated by `make codegen` from contracts/. Do not edit.\n\n';

await mkdir(out, { recursive: true });

for (const api of ['agent', 'gateway']) {
  const ast = await openapiTS(new URL(`openapi/${api}.yaml`, contracts));
  await writeFile(new URL(`${api}.ts`, out), banner + astToString(ast));
}

const messages = new URL('messages/', contracts);
const schemaFiles = (await readdir(messages))
  .filter((name) => name.endsWith('.schema.json'))
  .sort();
const types = await Promise.all(
  schemaFiles.map((name) =>
    compileFromFile(fileURLToPath(new URL(name, messages)), { bannerComment: '' }),
  ),
);
await writeFile(new URL('messages.ts', out), banner + types.join('\n'));

const sdlPath = fileURLToPath(new URL('graphql/schema.graphql', contracts));
const sdl = await readFile(sdlPath, 'utf8');
await writeFile(
  new URL('schema.ts', out),
  `${banner}export const typeDefs = ${JSON.stringify(sdl)};\n`,
);

// generate() is typed loosely; with saveToFile=false it returns the rendered files.
const [graphqlTypes] = (await generate(
  {
    schema: sdlPath,
    generates: {
      'graphql.ts': {
        plugins: ['typescript', 'typescript-resolvers'],
        // Type-only output: enums become unions so Node can strip the file without transpiling.
        config: { enumsAsTypes: true, useTypeImports: true },
      },
    },
    silent: true,
  },
  false,
)) as { content: string }[];
if (!graphqlTypes) throw new Error('graphql-codegen produced no output');
await writeFile(new URL('graphql.ts', out), banner + graphqlTypes.content);
