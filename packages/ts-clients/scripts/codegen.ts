// Regenerates src/generated/ and apps/web/src/generated/ from contracts/. Run through `make codegen`.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { generate } from '@graphql-codegen/cli';
import { compileFromFile } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';

const root = new URL('../../../', import.meta.url);
const contracts = new URL('contracts/', root);
const out = new URL('../src/generated/', import.meta.url);
const webOut = new URL('apps/web/src/generated/', root);
const banner = '// Generated by `make codegen` from contracts/. Do not edit.\n\n';
const path = (url: URL) => fileURLToPath(url).replaceAll('\\', '/');

// Start empty so output of deleted contracts disappears.
for (const dir of [out, webOut]) {
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
}

for (const api of ['agent', 'gateway']) {
  const ast = await openapiTS(new URL(`openapi/${api}.yaml`, contracts));
  await writeFile(new URL(`${api}.ts`, out), banner + astToString(ast));
}

// One type per message schema, a map from schema name to type, and the schemas for validation.
const messages = new URL('messages/', contracts);
const types: string[] = [];
const names: string[] = [];
const schemas: Record<string, unknown> = {};
for (const file of (await readdir(messages)).filter((f) => f.endsWith('.schema.json')).sort()) {
  const url = new URL(file, messages);
  const schema = JSON.parse(await readFile(url, 'utf8')) as { title: string };
  const name = file.replace(/\.schema\.json$/, '');
  // Types from other files are declared by their own schema, so declaring them here would clash.
  const refsOtherFiles = /"\$ref":"[^#]/.test(JSON.stringify(schema));
  types.push(
    await compileFromFile(fileURLToPath(url), {
      bannerComment: '',
      declareExternallyReferenced: !refsOtherFiles,
    }),
  );
  names.push(`  ${JSON.stringify(name)}: ${schema.title};`);
  schemas[name] = schema;
}
await writeFile(
  new URL('messages.ts', out),
  `${banner}${types.join('\n')}\nexport interface Messages {\n${names.join('\n')}\n}\n\n` +
    `export const schemas = ${JSON.stringify(schemas, null, 2)};\n`,
);

const sdlPath = path(new URL('graphql/schema.graphql', contracts));
const sdl = await readFile(sdlPath, 'utf8');
await writeFile(
  new URL('schema.ts', out),
  `${banner}export const typeDefs = ${JSON.stringify(sdl)};\n`,
);

const scalars = { DateTime: 'string' };
// generate() is typed loosely; with saveToFile=false it returns the rendered files.
const files = (await generate(
  {
    schema: sdlPath,
    generates: {
      // Gateway resolver types. Type-only output: enums become unions so Node can strip the file.
      [path(new URL('graphql.ts', out))]: {
        plugins: ['typescript', 'typescript-resolvers'],
        config: { enumsAsTypes: true, useTypeImports: true, strictScalars: true, scalars },
      },
      // Typed documents for the web's operations, sent as plain strings.
      [path(new URL('graphql.ts', webOut))]: {
        documents: path(new URL('apps/web/src/graphql/*.graphql', root)),
        plugins: ['typescript-operations', 'typed-document-node'],
        config: { documentMode: 'string', useTypeImports: true, strictScalars: true, scalars },
      },
    },
    silent: true,
  },
  false,
)) as { filename: string; content: string }[];
if (files.length !== 2) throw new Error('graphql-codegen did not render both outputs');
for (const { filename, content } of files) await writeFile(filename, banner + content);
